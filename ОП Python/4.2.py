N = int(input("Введите натуральное число N: "))
S = 0
for n in range(N + 1):
    form = ((-1) ** n) * (1 / (2 ** n)) #Формула для последовательности
    S += form
print(f"S = {S:.5f}")
# Контрольные числа 3; 4; 5 == 1 - 1 / 2 + 1 / 4 - 1 / 8 (при n = 3: 0.625) + 1 / 16 (при n = 4: 0.6875) - 1 / 32 (при n = 5: 0.65625)