while True:
    try:
        rinput = input("Введите числа через пробел (для дробных используйте точку): ").strip()
        
        # Проверка на пустой ввод
        if not rinput:
            print("Ошибка: Вы ничего не ввели. Попробуйте еще раз.")
            continue
        
        # Пытаемся преобразовать всё в float
        numbers = [float(x) for x in rinput.split()]
        
        # Если всё прошло успешно, считаем сумму и выходим из цикла
        total_sum = sum(numbers)
        print(f"\nУспешно! В последовательности {len(numbers)} элементов.")
        print(f"Сумма введенной последовательности: {total_sum}")
        break
        
    except ValueError:
        print("Ошибка: Обнаружен некорректный символ (буква или знак). Вводите только числа через пробел.")
